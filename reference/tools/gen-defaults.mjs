// One-off bootstrap: writes reference/src/categories.json from DEFAULT_CATEGORIES (src/state/categories.js)
// and reference/src/models/bucket-method.json from BUCKET_METHOD (src/calc/saving-model.js).
//   node reference/tools/gen-defaults.mjs [--force]
// It refuses to overwrite an existing file without --force: once real content enters, the files are edited by hand.

import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEFAULT_CATEGORIES } from '../../src/state/categories.js';
import { BUCKET_METHOD } from '../../src/calc/saving-model.js';
import { REF_DIR } from './build.mjs';

const force = process.argv.includes('--force');
const out = (rel, obj) => {
    const p = join(REF_DIR, 'src', rel);
    if (existsSync(p) && !force) { console.log(`skip ${rel} (exists; use --force)`); return; }
    mkdirSync(join(p, '..'), { recursive: true });
    writeFileSync(p, JSON.stringify(obj, null, 2) + '\n');
    console.log(`wrote ${rel}`);
};

const SRC = 'src/state/categories.js DEFAULT_CATEGORIES (generated by reference/tools/gen-defaults.mjs)';
out('categories.json', {
    schema: 1,
    rev: 1,
    keywordMatch: 'substring',
    categories: DEFAULT_CATEGORIES.map((c) => ({
        id: c.id,
        name: c.name,
        icon: c.icon,
        essential: c.essential,
        // A role, never a bucket id. Essential maps to daily and the rest to splurge (saving-model.js expenses-first rule); income has none.
        bucketRole: c.id === 'income' ? 'none' : (c.essential ? 'daily' : 'splurge'),
        keywords: [...c.keywords],
        source: SRC,
        reviewed: null,
    })),
});

const m = JSON.parse(JSON.stringify(BUCKET_METHOD));
out('models/bucket-method.json', {
    schema: 1,
    schemaVersion: 1,
    id: 'bucket-method',
    version: '1.0.0',
    meta: {
        title: 'Bucket method',
        blurb: 'Daily expenses first, then a share to Splurge, Smile and a Fire extinguisher. The default method, always available in the app.',
        after: m.after,
        source: 'src/calc/saving-model.js BUCKET_METHOD (generated by reference/tools/gen-defaults.mjs)',
        licence: 'app-default',
        reviewed: null,
        requires: { engine: m.engine },
    },
    model: m,
});
